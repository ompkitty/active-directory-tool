export function Select({ children }: any) { return <select>{children}</select> }
export function SelectContent({ children }: any) { return <>{children}</> }
export function SelectItem({ children }: any) { return <option>{children}</option> }
export function SelectTrigger({ children }: any) { return <div>{children}</div> }
export function SelectValue({ children }: any) { return <span>{children}</span> }
